"""The campaign manifest: what an experiment froze before its first episode.

[`09-run-manifest-rfc.md`](../../docs/agent-engineering/09-run-manifest-rfc.md)
§5.3 gives the campaign its own sealed record beside the per-episode ones,
and [`11-benchmark-data-registry-rfc.md`](../../docs/agent-engineering/11-benchmark-data-registry-rfc.md)
§13 lists what it must contain. This module implements that record and the
three identity rules the rest of the package leans on.

**The campaign id is derived, not drawn.** RFC 09 §4 says a campaign id is
new when the protocol, arm set, task set, aggregate cap or approval scope
changes. A random id satisfies that rule only if an operator remembers to
mint one; a digest of exactly those inputs satisfies it mechanically. So
`derive_campaign_id` hashes the protocol, the registry lock and the
lineage — which means raising a cap *cannot* resume the old campaign (the
id moved), and re-planning the same protocol against the same locked
registry lands on the same id and therefore resumes.

**The lock is the registry's word, not ours.** `CampaignLock` is W02's
object, generated by W02's resolver, and this module only carries it and
pins its digest. Nothing here can widen a selection, follow an alias or
substitute a case.

**Sealing is create-once.** `CampaignManifestStore` writes the manifest,
the lock and their digest sidecars, and refuses to write over any of them.
A campaign whose manifest was overwritten would be a campaign whose
denominators are unprovable.
"""

