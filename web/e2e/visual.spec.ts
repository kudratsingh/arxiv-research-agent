/**
 * WO-28 — the visual regression baselines.
 *
 * `00-DISCOVERY.md` listed "visual regression" among the missing quality
 * tiers. This file is that tier, and it is deliberately the smallest thing
 * that closes it: Playwright's own `toHaveScreenshot`, no new dependency, no
 * hosted service, no approval UI, and a committed PNG per render.
 *
 * WHAT IS COVERED, AND THE DEPTH LIMIT THAT COMES WITH IT.
 * Twelve renders × light/dark × 412/1440 = forty-eight snapshots. That is the
 * SLICE, not the matrix: `06-WORK-ORDERS.md` §4 has thirty-one rows, WO-27's
 * axe sweep walks twenty states at three widths in both themes, and a
 * screenshot at every one of those intersections would be a hundred and
 * twenty committed PNGs that a legitimate padding change invalidates in one
 * commit. `05-MIGRATION.md` §4.2 already lists visual-regression coverage
 * depth as an accepted residual risk; the entry recording it is
 * `docs/revamp/evidence/gate-4/residual-risks.md`, and criterion 3 is that
 * the limit is written down rather than discovered later.
 *
 * WHY THE ENGINE IS CHROMIUM AND ONLY CHROMIUM.
 * The same argument `playwright.config.ts` makes for `@axe`, `@cls` and
 * `@csp`, and it is stronger here than for any of them. Text rasterisation,
 * font hinting, scrollbar geometry and form-control metrics all differ
 * between Chromium, Gecko and WebKit — so a cross-engine snapshot set is
 * three sets of bytes that go stale independently and disagree for reasons
 * that are never product defects. Cross-engine rendering drift is exactly the
 * maintenance debt this work order is scoped to exclude. The engine limit is
 * not hidden: it is `@visual` in `CHROMIUM_ONLY`, and it is stated in
 * `e2e/README.md` and in the residual-risks entry.
 *
 * THE SAME ARGUMENT APPLIES TO THE PLATFORM, WHICH IS WHY IT IS IN THE PATH.
 * `playwright.config.ts` sets `snapshotPathTemplate` to include `{platform}`,
 * so this set lives under `e2e/__screenshots__/darwin/`. macOS and Linux
 * rasterise the same font at the same size differently; a single set shared
 * between them would fail on whichever host did not produce it, which is a
 * flaky gate rather than a strict one. A Linux set is generated by running
 * `e2e:visual:update` on Linux — see `e2e/README.md`, "Regenerating".
 *
 * A PLATFORM WITH NO COMMITTED SET **SKIPS**, LOUDLY, AND THAT IS THE HONEST
 * BEHAVIOUR. The `web-e2e` CI job runs `--project=chromium` on a Linux runner,
 * where `__screenshots__/linux/` does not exist because nobody has generated
 * and reviewed it. The three things that could happen there are: fail all
 * forty-eight for the absence of bytes nobody wrote (a red build that means
 * "no baseline", which is not a regression); let the runner write its own and
 * pass (a baseline the runner produced and immediately agreed with, which
 * proves nothing and is the worse of the two); or skip with a message naming
 * the command that would fix it. This file does the third, and
 * `no platform's baseline set is committed` below is the guard that stops the
 * skip from quietly becoming permanent everywhere. `--update-snapshots` turns
 * the skip off, because that IS the request to generate the set.
 *
 * DETERMINISM IS THE WHOLE PRODUCT HERE. A visual gate that goes red for
 * reasons other than a visual change is worse than no visual gate: it trains
 * everybody to regenerate on sight, and a set that is regenerated on sight
 * asserts nothing. The four measures are listed on `settleForCapture()` in
 * `support/capture.ts`,
 * each with the drift it removes — and measure 1 is there because this suite
 * flaked on its own second run before it existed.
 */

