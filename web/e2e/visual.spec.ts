/** Mirrors `snapshotPathTemplate` in `playwright.config.ts`. One meaning, two uses. */
const SNAPSHOT_ROOT = join(__dirname, "__screenshots__");

/** `{platform}` resolves to `process.platform` — `darwin`, `linux`, `win32`. */
const PLATFORM_DIR = join(SNAPSHOT_ROOT, process.platform);

/** Every platform that has one, for the guard test's message. */
function committedPlatforms(): string[] {
  if (!existsSync(SNAPSHOT_ROOT)) return [];
  return readdirSync(SNAPSHOT_ROOT, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
}

