/**
 * The one tolerance in this file, and the measurement behind it.
 *
 * FORTY-FIVE OF THE FORTY-EIGHT ARE BYTE-IDENTICAL between two forced
 * regenerations, and the three that are not differ by 4, 9 and 14 raw pixels —
 * below Playwright's own per-pixel `threshold`, so the comparator never even
 * counts them. The one render that moves enough for the comparator to see it
 * is `thread-populated` at 1440, and the cause was measured rather than
 * guessed:
 *
 *   * The briefing's `SectionRail` is `position: sticky` above 1280 px
 *     (`app/tokens.css`), and at 1440 it lays out at x = **1007.46875** — a
 *     fractional offset, the same one on every run (probed twelve times: the
 *     rect, the computed colour, the weight and the `aria-current` state are
 *     identical every time, so the DOM and the layout are deterministic).
 *   * A `sticky` box is a candidate for compositor promotion, and a promoted
 *     layer is rasterised snapped to whole device pixels while an unpromoted
 *     one is not. So the same two links are painted either at 1007.47 or at
 *     1007, half a pixel apart, and the run-to-run difference is that half
 *     pixel of glyph coverage: **124 pixels in dark, 131 in light**, bimodal,
 *     never any other value, in six full zero-tolerance runs (288
 *     comparisons). No other render failed a single comparison in those runs.
 *
 * Rejected fixes, and why. `--disable-lcd-text` on the chromium project —
 * tried, measured, made no difference, because this is subpixel *positioning*
 * and not the choice of antialiasing. Masking the rail — removes a real
 * surface from the gate to fix a rendering artefact. Injecting
 * `position: static` for the capture — makes the snapshot a picture of CSS
 * the product does not ship, and would then not notice if `sticky` were
 * removed.
 *
 * So it is a bound on the AREA that may differ, at 1.5× the largest value
 * ever observed. It is 0.015% of a 1440 × 900 frame, and the deliberate
 * 2 px shift criterion 2 asks for moves **two to three orders of magnitude**
 * more pixels than this — the PR body carries that number — so the tolerance
 * cannot swallow the regression the gate exists to catch. It bounds area
 * rather than raising `threshold`, deliberately: a colour change over a whole
 * surface stays red however small the per-pixel delta is.
 *
 * WO-D6 RE-MEASURED THIS OVER THREE FORCED REGENERATIONS AND THE BOUND STILL
 * HOLDS, with one addition worth recording rather than discovering later.
 * Forty-five of the forty-eight are byte-identical across all three. The
 * `thread-populated` pair at 1440 behaves exactly as described above —
 * bimodal, two of the three runs agreeing. The addition is `plan-review` at
 * 1440, which WO-S2 turned from a 30 px sliver of a clipped card into a
 * 742 px editor with six textareas: its left field borders carry the same
 * bimodal seam, 30 raw pixels in light and 39 in dark, at a **maximum
 * channel delta of 1 and 2**. That is an order of magnitude below the
 * per-pixel `threshold`, so Playwright counts zero differing pixels and the
 * comparator never sees it; it is recorded here because a future reader
 * measuring raw bytes will, and should know it is antialiasing on a new
 * surface rather than drift.
 */
const MAX_DIFF_PIXELS = 200;

