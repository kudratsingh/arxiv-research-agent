test.describe("WO-28 criterion 1 — the slice and the degraded states, light and dark, 412 and 1440", () => {
  for (const state of VISUAL_STATES) {
    for (const theme of THEMES) {
      for (const width of VISUAL_WIDTHS) {
        test(
          `${state.id} · ${theme} · ${width}px (§4 ${state.rows.join(", ")})`,
          { tag: "@visual" },
          async ({ page }, info) => {
            test.skip(
              !existsSync(PLATFORM_DIR) &&
                !REGENERATING.includes(info.config.updateSnapshots),
              `no committed snapshot set for platform "${process.platform}" ` +
                `(${PLATFORM_DIR}). This is not a regression and CI must not ` +
                "write its own baselines — a set the runner produced and then " +
                "agreed with proves nothing. Generate and REVIEW one with " +
                "`npm run e2e:visual:update` on this platform, commit it, and " +
                "these forty-eight comparisons start gating. See " +
                "e2e/README.md, 'Regenerating'.",
            );
            await page.setViewportSize({ width, height: A11Y_HEIGHTS[width] });
            // The theme axis, and the motion policy, in one call and before
            // any navigation. `emulateMedia` rather than the persisted
            // preference on purpose: `theme.spec.ts` pins a live defect in
            // which a stored `dark` is overwritten by the hydration pass, so
            // a snapshot suite that seeded `localStorage` would capture the
            // dark states in light half the time.
            await page.emulateMedia({ colorScheme: theme, reducedMotion: "reduce" });
            await state.arrange?.(page);
            await page.goto(state.path, { waitUntil: "domcontentloaded" });

            // Below `md` the rail is not in the layout and `ThreadRailBridge`
            // is not mounted until the drawer is asked for, so a rail state
            // captured without this is a picture of a page the state does not
            // occur on. At 1440 the rail is simply there.
            if (state.inRail === true && width < RAIL_ABSENT_BELOW) {
              await waitForRailMode(page, "drawer");
              await openRailDrawer(page);
            }
            await state.drive?.(page);

            // Never photograph a blank page — a screenshot of nothing is
            // stable, reproducible and worthless, which is how a visual gate
            // rots without anybody noticing.
            await expect(readyLocator(page, state.ready)).toBeVisible();
            // …and never photograph the wrong theme.
            await expect(page.locator("html")).toHaveAttribute("data-theme", theme);
            // …and never photograph a viewport the subject is not inside.
            if (state.scrollTo !== undefined) {
              await page.locator(state.scrollTo).first().scrollIntoViewIfNeeded();
            }
            await settleForCapture(page);

            await expect(page).toHaveScreenshot(`${state.id}-${theme}-${width}.png`, {
              // The viewport, not the document. `fullPage` on a long
              // briefing produces a several-thousand-pixel PNG whose bottom
              // is boilerplate, and every one of those pixels is committed
              // bytes and a chance to go red for nothing. The states whose
              // interest is below the fold have their own narrower renders.
              fullPage: false,
              // Set explicitly rather than left to the defaults, because
              // these three ARE the determinism argument and a default that
              // changes under us should change this file too.
              animations: "disabled",
              caret: "hide",
              scale: "css",
              // The one tolerance. See `MAX_DIFF_PIXELS` for the measurement.
              maxDiffPixels: MAX_DIFF_PIXELS,
            });
          },
        );
      }
    }
  }
});

