interface VisualState {
  /** Stable id. Becomes the first segment of the snapshot file name. */
  id: string;
  /** §4 rows this render covers. */
  rows: readonly string[];
  /** The `05 §2.1` slice step this render IS, or `null` for a degraded state. */
  step: 1 | 2 | 3 | 4 | 5 | null;
  /**
   * The retained Gate 1 screenshots this render is the successor to.
   *
   * Not decoration: the inventory test below asserts every name exists under
   * `docs/revamp/baseline/screenshots/`, which is what makes criterion 1's
   * phrase "with retained baseline screenshots" a checked property rather
   * than a claim. It is also the map a reviewer uses to put the old picture
   * beside the new one.
   */
  baseline: readonly string[];
  path: string;
  arrange?: (page: Page) => Promise<void>;
  inRail?: true;
  ready: ReadyCondition;
  /**
   * Anything that must happen AFTER navigation to reach the state.
   *
   * Exactly one row needs it, and `states.ts` explains why it has no such
   * field of its own: "a `StateEntry` describes a URL plus route
   * interception, not a script". A submission failure is a script — there is
   * no URL that renders it — so the script lives here rather than widening
   * that table for one row.
   */
  drive?: (page: Page) => Promise<void>;
  /**
   * The element that IS this render's subject, scrolled into view when the
   * viewport does not already contain it.
   *
   * ONE ROW NEEDS THIS AND IT WAS FOUND BY A DUPLICATE, NOT BY DESIGN.
   * `toBeVisible()` means "has a box and is not `visibility: hidden`", not "is
   * on screen", so `reconnecting` passed its ready condition at 412 with the
   * spine's announcement below the fold — and the captured viewport was
   * `running`'s, byte for byte. Two files, one picture, and one of them
   * asserting nothing. The `no two committed snapshots are identical` test
   * below is the permanent guard; this field is the fix.
   *
   * At 1440 the announcement is already on screen, so the scroll is a no-op
   * and that snapshot is unaffected.
   */
  scrollTo?: string;
}

/** One of WO-21's rows, by id, so no path or ready condition is re-typed. */
function row(id: string): StateEntry {
  const entry = STATES.find((state) => state.id === id);
  if (entry === undefined) {
    throw new Error(
      `support/states.ts has no "${id}" row. This file names states by id so a ` +
        "rename there fails here loudly instead of silently snapshotting the " +
        "wrong page.",
    );
  }
  return entry;
}

