class TestTheCommandLine:
    def test_packets_then_ingest_is_the_whole_workflow(
        self, tmp_path: Path, packet_set: PacketSet, capsys: pytest.CaptureFixture[str]
    ) -> None:
        assert main(["packets", "--output", str(tmp_path)]) == 0
        written = capsys.readouterr().out.splitlines()
        base = tmp_path / packet_set.packet_set_id
        assert written[0] == str(base / "expert-a" / "packet.json")
        assert written[2] == str(base / "manifest.json")

        decisions, _ = _synthetic_decisions(packet_set, "expert-a")
        labels = _write(
            tmp_path / "returned.json", _completed_packet(packet_set, "expert-a", decisions)
        )
        assert main(["ingest", str(labels), "--manifest", str(base / "manifest.json")]) == 0
        stdout = capsys.readouterr().out
        assert "# Offline calibration label report" in stdout
        assert "| all | 24 | 21/23" in stdout

        report_path = tmp_path / "reports" / "agreement.md"
        assert (
            main(
                [
                    "ingest",
                    str(labels),
                    "--manifest",
                    str(base / "manifest.json"),
                    "--output",
                    str(report_path),
                ]
            )
            == 0
        )
        assert report_path.read_text(encoding="utf-8").startswith(
            "# Offline calibration label report"
        )

    def test_a_seed_flag_moves_the_whole_set(self, tmp_path: Path) -> None:
        assert main(["packets", "--output", str(tmp_path), "--seed", "99"]) == 0

        assert [path.name for path in tmp_path.iterdir()] == [
            build_packet_set(seed=99).packet_set_id
        ]

    def test_a_refused_input_exits_two_and_says_why(
        self, tmp_path: Path, capsys: pytest.CaptureFixture[str]
    ) -> None:
        assert main(["packets", "--output", str(tmp_path)]) == 0
        capsys.readouterr()
        base = next(path for path in tmp_path.iterdir() if path.is_dir())
        malformed = tmp_path / "malformed.json"
        malformed.write_text("[]", encoding="utf-8")

        assert (
            main(["ingest", str(malformed), "--manifest", str(base / "manifest.json")]) == 2
        )
        assert "calibration input refused" in capsys.readouterr().err


