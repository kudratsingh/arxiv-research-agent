class TestWhatTheAnnotatorSees:
    def test_the_packets_carry_the_material_and_nothing_that_answers_it(
        self, packet_set: PacketSet
    ) -> None:
        cases = load_registered_cases()
        assert len(cases) == _ITEMS
        real_ids = {case.case_id for case in cases}
        blinded_ids = {case.blinded_item_id for case in cases}

        assert [packet.packet_id for packet in packet_set.packets] == list(PACKET_IDS)
        for packet in packet_set.packets:
            assert {item.blinded_item_id for item in packet.items} == blinded_ids
            assert packet.annotator_id is None
            assert packet.instructions == INSTRUCTIONS
            rendered = packet.model_dump_json()
            assert not real_ids.intersection(rendered.split('"'))
            for forbidden in (
                "expected_decision",
                "slice_tags",
                "case_id",
                "presentation_order",
                "rationale_id",
            ):
                assert forbidden not in rendered
            assert all(item.response == BlankResponse() for item in packet.items)

    def test_the_manifest_holds_the_key_and_not_the_answers(
        self, packet_set: PacketSet
    ) -> None:
        manifest = packet_set.manifest
        cases = {case.blinded_item_id: case for case in load_registered_cases()}

        assert manifest.handling == MANIFEST_HANDLING
        assert manifest.label_set_ref == "judge-calibration-expected-labels@1.0.0"
        assert manifest.blinding_plan_ref == "judge-calibration-blinding@1.0.0"
        rendered = manifest.model_dump_json()
        for case in cases.values():
            assert case.case_id in rendered
            assert case.expected_decision not in rendered.split('"')
        for key in manifest.packets:
            assert len(key.entries) == _ITEMS
            for entry in key.entries:
                assert entry.case_id == cases[entry.blinded_item_id].case_id
                assert entry.slice_tags == cases[entry.blinded_item_id].slice_tags

    def test_each_annotator_sees_one_order_and_the_set_sees_both(
        self, packet_set: PacketSet
    ) -> None:
        first, second = (
            {
                entry.blinded_item_id: entry.presentation_order
                for entry in packet_set.manifest.key_for(packet_id).entries
            }
            for packet_id in PACKET_IDS
        )
        pairwise = {item_id for item_id, order in first.items() if order is not None}

        assert len(pairwise) == _PAIRWISE_ITEMS
        for item_id in pairwise:
            assert {first[item_id], second[item_id]} == {"ab", "ba"}
        # Randomised, not assigned: neither packet is "the swapped one".
        assert len({first[item_id] for item_id in pairwise}) == 2

    def test_a_swapped_item_shows_the_two_excerpts_the_other_way_round(
        self, packet_set: PacketSet
    ) -> None:
        cases = {case.blinded_item_id: case for case in load_registered_cases()}
        swapped = 0
        for packet in packet_set.packets:
            entries = {
                entry.blinded_item_id: entry
                for entry in packet_set.manifest.key_for(packet.packet_id).entries
            }
            for item in packet.items:
                case = cases[item.blinded_item_id]
                if entries[item.blinded_item_id].presentation_order != "ba":
                    assert item.material.report_excerpt == case.material.report_excerpt
                    continue
                swapped += 1
                assert item.material.report_excerpt == case.material.second_excerpt
                assert item.material.second_excerpt == case.material.report_excerpt
        assert swapped == _PAIRWISE_ITEMS


