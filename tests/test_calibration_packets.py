def _decision_with(label_type: LabelType, outcome: bool) -> str:
    for value in decision_vocabulary(label_type):
        if binary_outcome(value) is outcome:
            return value
    raise AssertionError(f"{label_type} has no {outcome} decision")


def _synthetic_decisions(
    packet_set: PacketSet, packet_id: str
) -> tuple[dict[str, str], tuple[str, str, str]]:
    """A perfect annotator with exactly three deliberate errors.

    Returns the decisions *as the annotator would write them* — pairwise
    preferences in the order this packet displayed — plus the three ids
    that were perturbed, so a test can name them.
    """
    entries = {
        entry.blinded_item_id: entry
        for entry in packet_set.manifest.key_for(packet_id).entries
    }
    cases = {case.blinded_item_id: case for case in load_registered_cases()}
    binary_ids = sorted(
        item_id
        for item_id, entry in entries.items()
        if entry.label_type is not LabelType.PAIRWISE_PREFERENCE
    )
    fails = [
        item_id
        for item_id in binary_ids
        if binary_outcome(cases[item_id].expected_decision) is False
    ]
    passes = [
        item_id
        for item_id in binary_ids
        if binary_outcome(cases[item_id].expected_decision) is True
    ]
    assert len(fails) == _REFERENCE_FAILS
    assert len(passes) == _REFERENCE_PASSES
    false_pass_id, abstain_id = fails[0], fails[1]
    false_fail_id = passes[0]

    decisions: dict[str, str] = {}
    for item_id, entry in entries.items():
        expected = cases[item_id].expected_decision
        if item_id == false_pass_id:
            decisions[item_id] = _decision_with(entry.label_type, True)
        elif item_id == false_fail_id:
            decisions[item_id] = _decision_with(entry.label_type, False)
        elif item_id == abstain_id:
            decisions[item_id] = "abstain"
        elif entry.presentation_order == "ba" and expected in {"first", "second"}:
            decisions[item_id] = "second" if expected == "first" else "first"
        else:
            decisions[item_id] = expected
    return decisions, (false_pass_id, false_fail_id, abstain_id)


def _completed_packet(
    packet_set: PacketSet,
    packet_id: str,
    decisions: dict[str, str],
    *,
    annotator_id: str = "ann-expert1",
) -> dict[str, Any]:
    payload: dict[str, Any] = packet_set.packet(packet_id).model_dump(mode="json")
    payload["annotator_id"] = annotator_id
    for item in payload["items"]:
        item["response"] = {
            "decision": decisions[item["blinded_item_id"]],
            "confidence": "high",
            "rationale": "Synthetic decision generated by the test suite.",
        }
    return payload


def _label_file(
    packet_set: PacketSet,
    packet_id: str,
    decisions: dict[str, str],
    *,
    annotator_id: str = "ann-expert2",
) -> dict[str, Any]:
    entries = packet_set.manifest.key_for(packet_id).entries
    return {
        "schema_version": "1.0.0",
        "packet_id": packet_id,
        "annotator_id": annotator_id,
        "labels": [
            {
                "blinded_item_id": entry.blinded_item_id,
                "label_type": entry.label_type.value,
                "decision": decisions[entry.blinded_item_id],
                "confidence": "medium",
                "rationale": "Synthetic decision generated by the test suite.",
            }
            for entry in entries
        ],
    }


def _write(path: Path, payload: Any) -> Path:
    path.write_text(json.dumps(payload), encoding="utf-8")
    return path


