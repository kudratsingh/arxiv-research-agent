"""`GET /learn/paths*` — the flag, the gate, and the posture on the wire.

The gate tests are the point. WO-W15 c1 says "the endpoints never serve a
non-approved entry", and the only convincing way to assert that is to
build a content tree that *contains* unapproved entries and show they do
not come back.

Mutation-checked: changing `_detail` to read `manifest.entries` instead
of `manifest.servable_entries` fails
`test_a_withdrawn_entry_never_reaches_the_wire`; deleting the
`_require_enabled()` call from either handler fails the flag tests.
"""

