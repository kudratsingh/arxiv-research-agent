def _configure(
    monkeypatch: pytest.MonkeyPatch, *, enabled: bool, root: Path | None
) -> None:
    settings = Settings(
        enable_learn_content=enabled,
        learn_content_root=str(root) if root is not None else "",
    )
    monkeypatch.setattr("src.api.learn.settings", settings)
    monkeypatch.setattr("src.content.loader.settings", settings)
    loader.clear_cache()


