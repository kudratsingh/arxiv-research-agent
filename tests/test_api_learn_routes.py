class TestServingGate:
    async def test_a_withdrawn_entry_never_reaches_the_wire(
        self, monkeypatch: pytest.MonkeyPatch, tmp_path: Path
    ) -> None:
        """WO-W15 c1, at the boundary that matters.

        The published path holds a third entry that went `stale` — the
        post-publication case `02` §3.3 describes, where the path stays
        up and the row drops out. If `_detail` read `manifest.entries`
        instead of `servable_entries`, the dead row would ship.
        """
        root = tmp_path / "content"
        stale = _published_entry(
            3, "arxiv:2005.14165", "https://arxiv.org/abs/2005.14165"
        )
        stale["status"] = "stale"
        stale["staleness_note"] = "Link stopped resolving on 2026-08-30."
        _write_path(root, _manifest_document(entries=[*_manifest_document()["entries"], stale]))

        _configure(monkeypatch, enabled=True, root=root)
        async with _client() as client:
            body = (await client.get("/learn/paths/demo-path")).json()
        served = [e["resource_id"] for e in body["entries"]]
        assert served == ["arxiv:1706.03762", "arxiv:1810.04805"]
        assert "arxiv:2005.14165" not in json.dumps(body)

    async def test_a_path_awaiting_review_is_invisible(
        self, monkeypatch: pytest.MonkeyPatch, tmp_path: Path
    ) -> None:
        """An `approved`-but-not-published path is not half-served."""
        root = tmp_path / "content"
        entries = _manifest_document()["entries"]
        for entry in entries:
            entry["status"] = "approved"
        _write_path(root, _manifest_document(status="approved", entries=entries))
        _configure(monkeypatch, enabled=True, root=root)
        async with _client() as client:
            listing = await client.get("/learn/paths")
            detail = await client.get("/learn/paths/demo-path")
        assert listing.json() == {"paths": []}
        assert detail.status_code == 404

    async def test_no_response_body_contains_a_pdf_or_video_link(
        self, monkeypatch: pytest.MonkeyPatch, content_tree: Path
    ) -> None:
        """WO-W15 c2, asserted over the bytes a client actually receives."""
        _configure(monkeypatch, enabled=True, root=content_tree)
        async with _client() as client:
            listing = (await client.get("/learn/paths")).text
            detail = (await client.get("/learn/paths/demo-path")).text
        for payload in (listing, detail):
            assert "/pdf/" not in payload
            assert ".pdf" not in payload
            assert "youtube.com" not in payload
            assert "youtu.be" not in payload

    async def test_no_response_field_could_carry_full_text(
        self, monkeypatch: pytest.MonkeyPatch, content_tree: Path
    ) -> None:
        _configure(monkeypatch, enabled=True, root=content_tree)
        async with _client() as client:
            body = (await client.get("/learn/paths/demo-path")).json()
        for entry in body["entries"]:
            assert set(entry) & {
                "body",
                "full_text",
                "pdf_url",
                "transcript",
            } == set()


