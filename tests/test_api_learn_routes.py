def _entry(position: int, resource_id: str, url: str, **overrides: Any) -> dict[str, Any]:
    entry: dict[str, Any] = {
        "position": position,
        "resource_id": resource_id,
        "kind": "paper",
        "title": f"Paper {position}",
        "authors": ["A Name"],
        "author_count": 9,
        "year": 2020,
        "canonical_url": url,
        "license_note": "Link out to the arXiv abs page.",
        "attribution": "Someone et al. (arXiv.org)",
        "provenance": "curated",
        "status": "proposed",
        "rationale": "A rationale long enough to read like a sentence.",
        "vocabulary": ["a term"],
        "est_minutes": 60,
        "sequencing": {"method": "editorial", "cites": []},
    }
    entry.update(overrides)
    return entry


def _published_entry(
    position: int,
    resource_id: str,
    url: str,
    *,
    briefing_provenance: str = "generated",
) -> dict[str, Any]:
    return _entry(
        position,
        resource_id,
        url,
        status="published",
        reviewed_by="kudratsingh",
        reviewed_at="2026-08-30",
        briefing_file=f"briefings/{position:02d}.md",
        briefing_provenance=briefing_provenance,
    )


def _briefing_text(
    resource_id: str, path_id: str, provenance: str = "generated"
) -> str:
    generated = provenance == "generated"
    header = {
        "resource_id": resource_id,
        "path_id": path_id,
        "provenance": provenance,
        "label": (
            "generated, human-reviewed" if generated else "authored scaffolding"
        ),
        "briefing_version": 1,
        "generated_by": "job-test" if generated else None,
        "generated_at": "2026-08-30" if generated else None,
        "reviewed_by": "kudratsingh",
        "reviewed_at": "2026-08-30",
    }
    label = (
        "> **Generated by the learning agent, reviewed by kudratsingh.**"
        if generated
        else "> **FIXTURE CONTENT — authored placeholder, reviewed by kudratsingh.**"
    )
    body = f"{label}\n\nWhy this paper, why now: because the test needs a body.\n"
    return f"<!-- provenance\n{json.dumps(header)}\n-->\n\n{body}"


def _licensing() -> dict[str, Any]:
    return {
        "posture_id": "W-OD-3",
        "full_text": "link-out-only",
        "abstracts": "displayed-with-attribution",
        "quotes": "sparing-and-attributed",
        "s2_derived_facts": "link-back-required",
        "commercial_use": "none-through-phase-w",
        "counsel_confirmed": False,
        "source": "planning/07-learning-platform/02-CONTENT.md#22-papers",
    }


def _manifest_document(**overrides: Any) -> dict[str, Any]:
    document: dict[str, Any] = {
        "manifest_version": 1,
        "path_id": "demo-path",
        "kind": "flagship",
        "title": "Demo path",
        "goal": "Serve something.",
        "version": 3,
        "status": "published",
        "updated_at": "2026-08-30",
        "fixture": False,
        "licensing": _licensing(),
        "review": {
            "owner": "kudratsingh",
            "decisions": ["W-OD-3"],
            "curation_minutes_per_entry": 5,
        },
        "entries": [
            _published_entry(1, "arxiv:1706.03762", "https://arxiv.org/abs/1706.03762"),
            _published_entry(2, "arxiv:1810.04805", "https://arxiv.org/abs/1810.04805"),
        ],
    }
    document.update(overrides)
    return document


def _fixture_document(**overrides: Any) -> dict[str, Any]:
    """The labeled fixture path: banner required, briefings authored."""
    document = _manifest_document(
        path_id="fixture-demo",
        kind="fixture",
        fixture=True,
        banner="FIXTURE CONTENT. Demo scaffolding, not a reading path.",
        entries=[
            _published_entry(
                1,
                "arxiv:1706.03762",
                "https://arxiv.org/abs/1706.03762",
                briefing_provenance="authored",
            )
        ],
    )
    document.update(overrides)
    return document


def _write_path(root: Path, document: dict[str, Any]) -> Path:
    directory = root / "paths" / document["path_id"]
    (directory / "briefings").mkdir(parents=True)
    (directory / "path.json").write_text(json.dumps(document), encoding="utf-8")
    for entry in document["entries"]:
        if not entry.get("briefing_file"):
            continue
        (directory / entry["briefing_file"]).write_text(
            _briefing_text(
                entry["resource_id"],
                document["path_id"],
                entry["briefing_provenance"],
            ),
            encoding="utf-8",
        )
    return directory


def _write_published_tree(root: Path) -> None:
    """One published path, plus one still `proposed` so it can be hidden.

    The proposed path is the honest state of the real flagship path
    until its campaign runs, so "an unpublished path is invisible" is
    tested against the shape that actually ships.
    """
    _write_path(root, _manifest_document())
    _write_path(root, _fixture_document())
    _write_path(
        root,
        _manifest_document(
            path_id="draft-path",
            title="Draft path",
            status="proposed",
            entries=[
                _entry(1, "arxiv:2005.14165", "https://arxiv.org/abs/2005.14165")
            ],
        ),
    )


@pytest.fixture
def content_tree(tmp_path: Path) -> Path:
    root = tmp_path / "content"
    _write_published_tree(root)
    return root


