class TestLicensingPosture:
    def test_the_baseline_document_loads(self) -> None:
        """Guards the negative tests: they must differ by one thing only."""
        assert parse_manifest(_manifest()).path_id == "test-path"

    def test_a_pdf_link_is_refused(self) -> None:
        document = _manifest(
            entries=[
                _paper_entry(canonical_url="https://arxiv.org/pdf/1706.03762")
            ]
        )
        with pytest.raises(ContentValidationError) as exc:
            parse_manifest(document)
        assert _rule_of(exc) == schema.RULE_NO_FILE_URLS

    @pytest.mark.parametrize(
        "url",
        [
            "https://example.com/papers/attention.pdf",
            "https://arxiv.org/ftp/arxiv/papers/1706/1706.03762",
            "https://arxiv.org/e-print/1706.03762",
        ],
    )
    def test_every_file_shaped_url_is_refused(self, url: str) -> None:
        document = _manifest(entries=[_paper_entry(canonical_url=url)])
        with pytest.raises(ContentValidationError) as exc:
            parse_manifest(document)
        assert _rule_of(exc) == schema.RULE_NO_FILE_URLS

    def test_a_non_arxiv_paper_link_is_refused(self) -> None:
        """A mirror is not the abs page, however convenient it looks."""
        document = _manifest(
            entries=[
                _paper_entry(
                    canonical_url="https://www.semanticscholar.org/paper/abc",
                    resource_id="arxiv:1706.03762",
                )
            ]
        )
        with pytest.raises(ContentValidationError) as exc:
            parse_manifest(document)
        assert _rule_of(exc) == schema.RULE_ARXIV_ABS_ONLY

    def test_a_full_text_field_cannot_be_smuggled_in(self) -> None:
        document = _manifest(
            entries=[_paper_entry(full_text="the entire paper, pasted in")]
        )
        with pytest.raises(ContentValidationError) as exc:
            parse_manifest(document)
        assert _rule_of(exc) == schema.RULE_SCHEMA
        assert "full_text" in str(exc.value)

    def test_no_manifest_model_has_a_rehosting_field(self) -> None:
        """`L3` is a claim about the schema's shape, checked on the shape."""
        assert rehosting_fields(*MANIFEST_MODELS) == set()
        # And the list it is checked against is not empty, which would
        # make the assertion above vacuous.
        assert "full_text" in FORBIDDEN_FIELD_NAMES
        assert "pdf_url" in FORBIDDEN_FIELD_NAMES
        assert "transcript" in FORBIDDEN_FIELD_NAMES

    def test_an_abstract_without_attribution_is_refused(self) -> None:
        document = _manifest(
            entries=[
                _paper_entry(
                    abstract={
                        "text": "The dominant sequence transduction models...",
                        "url": "https://arxiv.org/abs/1706.03762",
                    }
                )
            ]
        )
        with pytest.raises(ContentValidationError) as exc:
            parse_manifest(document)
        assert _rule_of(exc) == schema.RULE_SCHEMA
        assert "source" in str(exc.value)

    def test_an_abstract_must_link_to_its_own_abs_page(self) -> None:
        document = _manifest(
            entries=[
                _paper_entry(
                    abstract={
                        "text": "An abstract belonging to a different paper.",
                        "source": "arXiv.org",
                        "url": "https://arxiv.org/abs/1810.04805",
                    }
                )
            ]
        )
        with pytest.raises(ContentValidationError) as exc:
            parse_manifest(document)
        assert _rule_of(exc) == schema.RULE_ABSTRACT_ATTRIBUTED

    def test_an_attributed_abstract_loads(self) -> None:
        document = _manifest(
            entries=[
                _paper_entry(
                    abstract={
                        "text": "An abstract, quoted with its attribution.",
                        "source": "arXiv.org (CC0 metadata)",
                        "url": "https://arxiv.org/abs/1706.03762",
                    }
                )
            ]
        )
        manifest = parse_manifest(document)
        assert manifest.entries[0].abstract is not None
        assert manifest.entries[0].abstract.source.startswith("arXiv.org")

    def test_a_citation_ancestry_claim_must_link_back_to_s2(self) -> None:
        document = _manifest(
            entries=[
                _paper_entry(
                    position=1,
                    resource_id="arxiv:1409.3215",
                    canonical_url="https://arxiv.org/abs/1409.3215",
                    sequencing={"method": "citation_ancestry", "cites": []},
                )
            ]
        )
        with pytest.raises(ContentValidationError) as exc:
            parse_manifest(document)
        assert _rule_of(exc) == schema.RULE_S2_LINKS_BACK

    def test_a_link_back_must_actually_point_at_s2(self) -> None:
        document = _manifest(
            entries=[
                _paper_entry(),
                _paper_entry(
                    position=2,
                    resource_id="arxiv:1810.04805",
                    canonical_url="https://arxiv.org/abs/1810.04805",
                    sequencing={
                        "method": "citation_ancestry",
                        "cites": ["arxiv:1706.03762"],
                        "evidence_url": "https://example.com/i-promise",
                    },
                ),
            ]
        )
        with pytest.raises(ContentValidationError) as exc:
            parse_manifest(document)
        assert _rule_of(exc) == schema.RULE_S2_LINKS_BACK

    def test_youtube_is_refused_wherever_it_appears(self) -> None:
        """`L7` — the 30-day metadata clock a git file cannot honour."""
        document = _manifest(
            entries=[
                _paper_entry(
                    kind="external_course",
                    resource_id="ext:some-video",
                    canonical_url="https://www.youtube.com/watch?v=abcdefghijk",
                )
            ]
        )
        with pytest.raises(ContentValidationError) as exc:
            parse_manifest(document)
        assert _rule_of(exc) == schema.RULE_NO_YOUTUBE

    def test_the_video_kind_does_not_exist_in_phase_w(self) -> None:
        document = _manifest(entries=[_paper_entry(kind="video")])
        with pytest.raises(ContentValidationError):
            parse_manifest(document)

    def test_a_copyleft_link_out_must_name_its_licence_url(self) -> None:
        document = _manifest(
            entries=[
                _paper_entry(
                    kind="external_course",
                    resource_id="ext:ocw-thing",
                    canonical_url="https://ocw.mit.edu/courses/some-course/",
                    license_id="CC BY-NC-SA-4.0",
                )
            ]
        )
        with pytest.raises(ContentValidationError) as exc:
            parse_manifest(document)
        assert _rule_of(exc) == schema.RULE_NONCOMMERCIAL

    @pytest.mark.parametrize(
        "field,value",
        [
            ("full_text", "we-host-it-now"),
            ("commercial_use", "allowed"),
            ("s2_derived_facts", "no-link-needed"),
        ],
    )
    def test_the_posture_block_admits_exactly_one_value_per_field(
        self, field: str, value: str
    ) -> None:
        """W-OD-3 is an assertion the manifest makes, not a knob."""
        document = _manifest()
        document["licensing"][field] = value
        with pytest.raises(ContentValidationError):
            parse_manifest(document)

    def test_the_resource_id_must_agree_with_the_link(self) -> None:
        document = _manifest(entries=[_paper_entry(resource_id="arxiv:1810.04805")])
        with pytest.raises(ContentValidationError) as exc:
            parse_manifest(document)
        assert _rule_of(exc) == schema.RULE_ID_MATCHES_URL


