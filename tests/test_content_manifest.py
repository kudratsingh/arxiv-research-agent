"""The licensing posture and the status queue, asserted as behaviour.

WO-W15 acceptance criteria 1, 2 and 5 are all of the form "the rule is in
code, not in prose". These tests are the evidence: each one takes a
manifest that breaks exactly one rule and shows it does not load.

Mutation-checked: deleting the `L1_ARXIV_ABS_ONLY` block from
`Entry._posture` fails `test_a_pdf_link_is_refused`; deleting the
`S1_REVIEW_REQUIRED` block fails
`test_approved_without_a_reviewer_is_refused`; relaxing `extra="forbid"`
on `_Strict` fails `test_a_full_text_field_cannot_be_smuggled_in`.
"""

