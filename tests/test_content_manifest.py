def _paper_entry(**overrides: Any) -> dict[str, Any]:
    entry: dict[str, Any] = {
        "position": 1,
        "resource_id": "arxiv:1706.03762",
        "kind": "paper",
        "title": "Attention Is All You Need",
        "authors": ["Ashish Vaswani"],
        "author_count": 8,
        "year": 2017,
        "canonical_url": "https://arxiv.org/abs/1706.03762",
        "license_note": "Link out to the arXiv abs page.",
        "attribution": "Vaswani et al. (arXiv.org)",
        "provenance": "curated",
        "status": "proposed",
        "rationale": "A rationale long enough to be a sentence.",
        "vocabulary": ["self-attention"],
        "est_minutes": 90,
        "sequencing": {"method": "editorial", "cites": []},
    }
    entry.update(overrides)
    return entry


def _manifest(**overrides: Any) -> dict[str, Any]:
    document: dict[str, Any] = {
        "manifest_version": 1,
        "path_id": "test-path",
        "kind": "flagship",
        "title": "Test path",
        "goal": "Prove the schema refuses what it says it refuses.",
        "version": 1,
        "status": "proposed",
        "updated_at": "2026-08-30",
        "fixture": False,
        "licensing": {
            "posture_id": "W-OD-3",
            "full_text": "link-out-only",
            "abstracts": "displayed-with-attribution",
            "quotes": "sparing-and-attributed",
            "s2_derived_facts": "link-back-required",
            "commercial_use": "none-through-phase-w",
            "counsel_confirmed": False,
            "source": "planning/07-learning-platform/02-CONTENT.md#22-papers",
        },
        "review": {
            "owner": "kudratsingh",
            "decisions": ["W-OD-3"],
            "curation_minutes_per_entry": 10,
        },
        "entries": [_paper_entry()],
    }
    document.update(overrides)
    return document


def _briefing(header: dict[str, Any] | None = None, body: str | None = None) -> str:
    head: dict[str, Any] = {
        "resource_id": "arxiv:1706.03762",
        "path_id": "test-path",
        "provenance": "generated",
        "label": "generated, human-reviewed",
        "briefing_version": 1,
        "generated_by": "job-abc123",
        "generated_at": "2026-08-30",
        "reviewed_by": "kudratsingh",
        "reviewed_at": "2026-08-30",
    }
    if header is not None:
        head.update(header)
    text = body if body is not None else (
        "> **Generated by the learning agent, reviewed by kudratsingh.**\n\n"
        "Body prose that says something about the paper.\n"
    )
    return f"<!-- provenance\n{json.dumps(head, indent=2)}\n-->\n\n{text}"


def _rule_of(exc: pytest.ExceptionInfo[ContentValidationError]) -> str:
    return exc.value.rule


