class TestBriefingProvenance:
    def test_a_valid_briefing_parses(self) -> None:
        briefing = parse_briefing(_briefing())
        assert briefing.header.generated_by == "job-abc123"
        assert briefing.body.startswith("> **Generated by the learning agent")

    def test_a_briefing_without_a_header_is_refused(self) -> None:
        with pytest.raises(ContentValidationError) as exc:
            parse_briefing("# Just a markdown file\n")
        assert _rule_of(exc) == schema.RULE_BRIEFING_REQUIRED

    def test_a_generated_briefing_must_name_its_run(self) -> None:
        with pytest.raises(ContentValidationError) as exc:
            parse_briefing(_briefing({"generated_by": None}))
        assert _rule_of(exc) == schema.RULE_GENERATED_NEEDS_RUN

    def test_the_generated_label_is_fixed_by_02(self) -> None:
        with pytest.raises(ContentValidationError) as exc:
            parse_briefing(_briefing({"label": "written by a human, honest"}))
        assert _rule_of(exc) == schema.RULE_GENERATED_NEEDS_RUN

    def test_the_display_label_must_be_the_first_visible_line(self) -> None:
        text = _briefing(body="Straight into the prose, no label anywhere.\n")
        with pytest.raises(ContentValidationError) as exc:
            schema.check_display_label(parse_briefing(text))
        assert _rule_of(exc) == schema.RULE_GENERATED_NEEDS_RUN

    def test_an_unattributed_block_quote_is_refused(self) -> None:
        text = _briefing(
            body=(
                "> **Generated by the learning agent, reviewed by kudratsingh.**\n\n"
                "As the paper says:\n\n"
                "> A sentence lifted straight out of the paper.\n\n"
                "And on we go.\n"
            )
        )
        with pytest.raises(ContentValidationError) as exc:
            schema.check_quotes(parse_briefing(text))
        assert _rule_of(exc) == schema.RULE_QUOTES_ATTRIBUTED

    def test_an_attributed_block_quote_passes(self) -> None:
        text = _briefing(
            body=(
                "> **Generated by the learning agent, reviewed by kudratsingh.**\n\n"
                "As the paper says:\n\n"
                "> A sentence lifted straight out of the paper.\n\n"
                "— Vaswani et al., https://arxiv.org/abs/1706.03762\n\n"
                "And on we go.\n"
            )
        )
        schema.check_quotes(parse_briefing(text))

    def test_quoting_too_much_is_refused_even_when_attributed(self) -> None:
        quote = "\n".join(f"> Quoted line number {i} of the paper." for i in range(60))
        text = _briefing(
            body=(
                "> **Generated by the learning agent, reviewed by kudratsingh.**\n\n"
                f"{quote}\n\n"
                "— Vaswani et al., https://arxiv.org/abs/1706.03762\n"
            )
        )
        with pytest.raises(ContentValidationError) as exc:
            schema.check_quotes(parse_briefing(text))
        assert _rule_of(exc) == schema.RULE_QUOTES_ATTRIBUTED

    @pytest.mark.parametrize(
        "url,rule",
        [
            ("https://arxiv.org/pdf/1706.03762", schema.RULE_NO_FILE_URLS),
            ("https://www.youtube.com/watch?v=abcdefghijk", schema.RULE_NO_YOUTUBE),
        ],
    )
    def test_a_briefing_may_not_link_to_a_file_or_a_video(
        self, url: str, rule: str
    ) -> None:
        text = _briefing(
            body=(
                "> **Generated by the learning agent, reviewed by kudratsingh.**\n\n"
                f"See {url} for the details.\n"
            )
        )
        with pytest.raises(ContentValidationError) as exc:
            schema.check_briefing_urls(parse_briefing(text))
        assert _rule_of(exc) == rule


