    def test_the_content_tree_reaches_the_image(self) -> None:
        """The failure the schema cannot catch: right manifest, no files.

        `.dockerignore` strips `*.md` from the build context, which would
        take every briefing companion with it, and `content/` is not
        under `src/` so `COPY src ./src` does not carry it either. Both
        halves are text in files no Python test would otherwise reach.
        """
        root = default_content_root().parent
        dockerfile = (root / "Dockerfile").read_text(encoding="utf-8")
        ignore = (root / ".dockerignore").read_text(encoding="utf-8")
        assert "COPY content ./content" in dockerfile
        assert "!content/**/*.md" in ignore
        # And the negation has to come *after* the blanket rule, since
        # the last matching pattern wins.
        assert ignore.index("*.md\n") < ignore.index("!content/**/*.md")

    def test_the_shipped_manifests_survive_a_round_trip(self) -> None:
        """Nothing in the files depends on key order or on pydantic defaults."""
        root = default_content_root()
        for document in (root / "paths").glob("*/path.json"):
            payload = json.loads(document.read_text(encoding="utf-8"))
            manifest = parse_manifest(copy.deepcopy(payload))
            again = parse_manifest(manifest.model_dump(mode="json"))
            assert again == manifest
