def _write_path(tmp_path: Path, document: dict[str, Any]) -> Path:
    directory = tmp_path / "paths" / document["path_id"]
    (directory / "briefings").mkdir(parents=True)
    (directory / "path.json").write_text(json.dumps(document), encoding="utf-8")
    return directory


class TestLoaderCrossChecks:
    def test_an_approved_entry_with_no_briefing_file_on_disk_fails(
        self, tmp_path: Path
    ) -> None:
        document = _manifest(
            entries=[
                _paper_entry(
                    status="approved",
                    reviewed_by="kudratsingh",
                    reviewed_at="2026-08-30",
                    briefing_file="briefings/missing.md",
                    briefing_provenance="generated",
                )
            ]
        )
        directory = _write_path(tmp_path, document)
        with pytest.raises(ContentValidationError) as exc:
            load_path_dir(directory)
        assert _rule_of(exc) == schema.RULE_BRIEFING_REQUIRED

    def test_a_briefing_claiming_a_reviewer_the_manifest_does_not_fails(
        self, tmp_path: Path
    ) -> None:
        """The forgery direction: a file that says it was reviewed."""
        document = _manifest(
            entries=[
                _paper_entry(
                    briefing_file="briefings/x.md", briefing_provenance="generated"
                )
            ]
        )
        directory = _write_path(tmp_path, document)
        (directory / "briefings" / "x.md").write_text(_briefing(), encoding="utf-8")
        with pytest.raises(ContentValidationError) as exc:
            load_path_dir(directory)
        assert _rule_of(exc) == schema.RULE_REVIEW_REQUIRED

    def test_an_undrafted_briefing_on_a_proposed_entry_is_fine(
        self, tmp_path: Path
    ) -> None:
        """The normal pre-campaign state: a target, not yet a file."""
        document = _manifest(
            entries=[
                _paper_entry(
                    briefing_file="briefings/not-yet.md",
                    briefing_provenance="generated",
                )
            ]
        )
        path = load_path_dir(_write_path(tmp_path, document))
        assert path.briefings == {}
        assert path.manifest.servable_entries == []

    def test_the_manifest_must_live_in_a_directory_named_for_it(
        self, tmp_path: Path
    ) -> None:
        document = _manifest()
        directory = _write_path(tmp_path, document)
        renamed = directory.parent / "some-other-name"
        directory.rename(renamed)
